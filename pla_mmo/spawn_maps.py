"""Local fixed-alpha location map data.

The map payload is generated by ``tools/build_spawn_maps.py`` into
``cache/spawn-maps``. This module only reads it at runtime; Serebii is never
contacted by the app.
"""

from __future__ import annotations

import json
import threading
from pathlib import Path

from pla_mmo.paths import get_project_root

MAP_ROOT = get_project_root() / "cache" / "spawn-maps"
MAP_DATA_PATH = MAP_ROOT / "maps.json"
BINDINGS_PATH = MAP_ROOT / "bindings.json"
# Bundled fallback so a fresh install does not have to download map images.
BUNDLED_MAP_ROOT = get_project_root() / "static" / "spawn-maps"
BUNDLED_MAP_DATA_PATH = BUNDLED_MAP_ROOT / "maps.json"


class SpawnMapStore:
    def __init__(self) -> None:
        self.root = MAP_ROOT
        self.path = MAP_DATA_PATH
        self.bindings_path = BINDINGS_PATH
        self._lock = threading.RLock()
        self._data: dict | None = None
        self._bindings: dict[str, str] = {}
        self._load_bindings()

    def _load_bindings(self) -> None:
        try:
            data = json.loads(self.bindings_path.read_text(encoding="utf-8"))
            if isinstance(data, dict):
                self._bindings = {
                    str(key): str(value)
                    for key, value in data.items()
                    if str(key) and str(value)
                }
        except (OSError, ValueError, TypeError):
            self._bindings = {}

    def _load(self) -> dict:
        with self._lock:
            if self._data is not None:
                return self._data
            loaded = False
            for path in (self.path, BUNDLED_MAP_DATA_PATH):
                try:
                    data = json.loads(path.read_text(encoding="utf-8"))
                    loaded = True
                    break
                except (OSError, ValueError):
                    continue
            if not loaded:
                data = {"maps": []}
            if not isinstance(data, dict):
                data = {"maps": []}
            maps = []
            for entry in data.get("maps") or []:
                if not isinstance(entry, dict) or not entry.get("key"):
                    continue
                maps.append(entry)
            self._data = {
                "source": str(data.get("source") or ""),
                "width": int(data.get("width") or 2048),
                "height": int(data.get("height") or 2048),
                "maps": maps,
            }
            return self._data

    def catalog(self) -> dict:
        data = self._load()
        maps = []
        for entry in data["maps"]:
            maps.append({
                "key": entry.get("key"),
                "label": entry.get("label"),
                "image": f"/api/spawns/map-image/{entry.get('key')}",
                "width": data["width"],
                "height": data["height"],
                "points": [self._public_point(point) for point in entry.get("points") or []],
            })
        return {
            "ok": True,
            "source": data["source"],
            "maps": maps,
            "bindings": dict(self._bindings),
        }

    def _public_point(self, point: dict) -> dict:
        if not isinstance(point, dict):
            return {}
        point_id = str(point.get("id") or "")
        bound = self._bindings.get(point_id)
        spawners = [str(value) for value in point.get("spawners") or [] if value]
        if bound and bound in spawners:
            spawners = [bound]
        return {
            "id": point_id,
            "species": str(point.get("species") or ""),
            "national": int(point.get("national") or 0),
            "x": float(point.get("x") or 0),
            "y": float(point.get("y") or 0),
            "gender_ratio": int(point.get("gender_ratio") if point.get("gender_ratio") is not None else 255),
            "times": [str(value) for value in point.get("times") or ["any"]],
            "spawners": spawners,
            "bound": bool(bound and bound in spawners),
            "alpha": bool(point.get("alpha", False)),
            "area": str(point.get("area") or ""),
        }

    def image_path(self, map_key: str) -> Path | None:
        entry = self._entry(map_key)
        if entry is None:
            return None
        image = str(entry.get("image") or "")
        if not image or Path(image).name != image:
            return None
        path = self.root / image
        if path.is_file():
            return path
        bundled = BUNDLED_MAP_ROOT / image
        return bundled if bundled.is_file() else None

    def bind(self, point_id: str, spawner: str) -> dict:
        point_id = str(point_id or "").strip()
        spawner = str(spawner or "").strip()
        if not point_id or not spawner:
            return {"ok": False, "error": "缺少地图点或 spawner。"}
        point = self._point(point_id)
        if point is None:
            return {"ok": False, "error": "找不到该地图点。"}
        allowed = {str(value) for value in point.get("spawners") or []}
        if spawner not in allowed:
            return {"ok": False, "error": "该 spawner 不属于这个地图点。"}
        with self._lock:
            self._bindings[point_id] = spawner
            try:
                self.root.mkdir(parents=True, exist_ok=True)
                self.bindings_path.write_text(
                    json.dumps(self._bindings, ensure_ascii=False, indent=2),
                    encoding="utf-8",
                )
            except OSError as exc:
                return {"ok": False, "error": f"保存位置映射失败：{exc}"}
        return {"ok": True, "point_id": point_id, "spawner": spawner}

    def _entry(self, map_key: str) -> dict | None:
        data = self._load()
        return next((entry for entry in data["maps"] if entry.get("key") == map_key), None)

    def _point(self, point_id: str) -> dict | None:
        data = self._load()
        for entry in data["maps"]:
            for point in entry.get("points") or []:
                if point.get("id") == point_id:
                    return point
        return None
